# 菜单按钮 (35, 329)
TD_MENU='\000\000\000\000\000\000\000\000\003\000\057\000\000\000\000\000\000\000\000\000\000\000\000\000\003\000\071\000\012\000\000\000\000\000\000\000\000\000\000\000\003\000\065\000\043\000\000\000\000\000\000\000\000\000\000\000\003\000\066\000\111\001\000\000\000\000\000\000\000\000\000\000\001\000\112\001\001\000\000\000\000\000\000\000\000\000\000\000\003\000\000\000\043\000\000\000\000\000\000\000\000\000\000\000\003\000\001\000\111\001\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'

# 返回按钮 (34, 30)
TD_BACK='\000\000\000\000\000\000\000\000\003\000\057\000\000\000\000\000\000\000\000\000\000\000\000\000\003\000\071\000\012\000\000\000\000\000\000\000\000\000\000\000\003\000\065\000\042\000\000\000\000\000\000\000\000\000\000\000\003\000\066\000\036\000\000\000\000\000\000\000\000\000\000\000\001\000\112\001\001\000\000\000\000\000\000\000\000\000\000\000\003\000\000\000\042\000\000\000\000\000\000\000\000\000\000\000\003\000\001\000\036\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'

# 模式切换 (44, 25)
TD_MODE='\000\000\000\000\000\000\000\000\003\000\057\000\000\000\000\000\000\000\000\000\000\000\000\000\003\000\071\000\012\000\000\000\000\000\000\000\000\000\000\000\003\000\065\000\054\000\000\000\000\000\000\000\000\000\000\000\003\000\066\000\031\000\000\000\000\000\000\000\000\000\000\000\001\000\112\001\001\000\000\000\000\000\000\000\000\000\000\000\003\000\000\000\054\000\000\000\000\000\000\000\000\000\000\000\003\000\001\000\031\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'

# 退出按钮 (603, 329)
TD_EXIT='\000\000\000\000\000\000\000\000\003\000\057\000\000\000\000\000\000\000\000\000\000\000\000\000\003\000\071\000\012\000\000\000\000\000\000\000\000\000\000\000\003\000\065\000\133\002\000\000\000\000\000\000\000\000\000\000\003\000\066\000\111\001\000\000\000\000\000\000\000\000\000\000\001\000\112\001\001\000\000\000\000\000\000\000\000\000\000\000\003\000\000\000\133\002\000\000\000\000\000\000\000\000\000\000\003\000\001\000\111\001\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'

# 分辨率菜单项 (320, 171)
TD_RES='\000\000\000\000\000\000\000\000\003\000\057\000\000\000\000\000\000\000\000\000\000\000\000\000\003\000\071\000\012\000\000\000\000\000\000\000\000\000\000\000\003\000\065\000\100\001\000\000\000\000\000\000\000\000\000\000\003\000\066\000\253\000\000\000\000\000\000\000\000\000\000\000\001\000\112\001\001\000\000\000\000\000\000\000\000\000\000\000\003\000\000\000\100\001\000\000\000\000\000\000\000\000\000\000\003\000\001\000\253\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'

# 触摸 UP (64 bytes, 共用)
TU='\000\000\000\000\000\000\000\000\003\000\057\000\000\000\000\000\000\000\000\000\000\000\000\000\003\000\071\000\377\377\377\377\000\000\000\000\000\000\000\000\001\000\112\001\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'

# 硬件键 (32 bytes each)
# KEY_DOWN(108) press/release
KD_DN='\000\000\000\000\000\000\000\000\001\000\154\000\001\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'
KD_UP='\000\000\000\000\000\000\000\000\001\000\154\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'
# KEY_OK(352) press/release
KO_DN='\000\000\000\000\000\000\000\000\001\000\140\001\001\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'
KO_UP='\000\000\000\000\000\000\000\000\001\000\140\001\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'

# ========== 注入函数 ==========

tap() {
    printf "%b" "$1" > /tmp/_td.bin
    printf "%b" "$TU" > /tmp/_tu.bin
    cat /tmp/_td.bin > "$TOUCH"
    sleep 0.15
    cat /tmp/_tu.bin > "$TOUCH"
}

key_press() {
    printf "%b" "$1" > /tmp/_kd.bin
    printf "%b" "$2" > /tmp/_ku.bin
    cat /tmp/_kd.bin > "$KEY"
    sleep 0.1
    cat /tmp/_ku.bin > "$KEY"
}

press_down() {
    key_press "$KD_DN" "$KD_UP"
}

press_ok() {
    key_press "$KO_DN" "$KO_UP"
}

log() {
    echo "[$(date '+%H:%M:%S')] $1"
}

# ========== 操作序列 ==========

switch_res_next2() {
    # 进入分辨率列表，按 DOWN 2次选中当前后第2个，按 OK 确认
    tap "$TD_RES"
    sleep 1
    press_down; sleep 0.2
    press_down; sleep 0.2
    press_ok
    sleep 1
}

take_photo() {
    # 按 KEY_OK 拍照，等待完成
    press_ok
    sleep 2
}

record_video_4s() {
    # KEY_OK 开始录像，等 4 秒，KEY_OK 停止
    press_ok
    sleep 4
    press_ok
    sleep 1
}

# ========== 主循环 ==========

log "===== PT100 分辨率切换+拍照录像循环测试 ====="
log "每轮：切后2个拍照分辨率→拍照→切后2个录像分辨率→录4s"
log "循环次数: ${LOOP_COUNT}（0=无限）"
log ""

cycle=0
while true; do
    cycle=$((cycle + 1))
    if [ "$LOOP_COUNT" -gt 0 ] && [ "$cycle" -gt "$LOOP_COUNT" ]; then
        break
    fi

    log "===== 第 $cycle 轮 ====="

    # 1. 主菜单 → AI夜视仪
    log "[1] 主菜单 → AI夜视仪"
    tap "$TD_AI"
    sleep 2

    # 2. 打开拍照菜单
    log "[2] 打开拍照菜单"
    tap "$TD_MENU"
    sleep 1

    # 3. 切换分辨率（当前后第2个）
    log "[3] 切换拍照分辨率(+2)"
    switch_res_next2

    # 4. 返回相机视图
    log "[4] 返回相机视图"
    tap "$TD_BACK"
    sleep 1

    # 5. 拍照
    log "[5] 拍照"
    take_photo

    # 6. 切换到录像模式
    log "[6] 切换到录像模式"
    tap "$TD_MODE"
    sleep 2

    # 7. 打开录像菜单
    log "[7] 打开录像菜单"
    tap "$TD_MENU"
    sleep 1

    # 8. 切换录像分辨率（当前后第2个）
    log "[8] 切换录像分辨率(+2)"
    switch_res_next2

    # 9. 返回相机视图
    log "[9] 返回相机视图"
    tap "$TD_BACK"
    sleep 1

    # 10. 录4秒视频
    log "[10] 录像4秒"
    record_video_4s

    # 11. 切换回拍照模式
    log "[11] 切换回拍照模式"
    tap "$TD_MODE"
    sleep 2

    # 12. 返回主菜单
    log "[12] 返回主菜单"
    tap "$TD_EXIT"
    sleep 2

    log "===== 第 $cycle 轮完成 ====="
    log ""
done

log "===== 测试结束，共完成 $((cycle - 1)) 轮 ====="
